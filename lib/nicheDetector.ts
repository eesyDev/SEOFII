/**
 * Определяет нишу по ключевому слову и SERP-заголовкам конкурентов.
 * Возвращает slug ниши или "general" если ничего не распознано.
 */
export function detectNiche(
  targetKeyword: string,
  serpTitles: string[] = [],
  siteType?: SiteType
): string {
  const haystack = [targetKeyword, ...serpTitles].join(" ").toLowerCase();

  let bestNiche = "general";
  let bestScore = 0;

  for (const { niche, signals } of NICHE_SIGNALS) {
    const score = signals.filter((s) => haystack.includes(s)).length;
    if (score > bestScore) {
      bestScore = score;
      bestNiche = niche;
    }
  }

  if (bestScore === 0) {
    // Если E-commerce сайт но ниша не определена — хотя бы используем общую метку
    if (siteType === "ecommerce") return "ecommerce_general";
    return "general";
  }

  return bestNiche;
}
